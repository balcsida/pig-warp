const (
	statusKey         = "branch-out-terminal"
	launchType        = "branch-out-launch"
	launchAppliedType = "branch-out-launch-applied"
	autoSubmitSeconds = 10
	reservedTemplate  = "{{autogenerated_branch_name}}" // Warp substitutes it in Tab Configs (index.ts:1136)
)

// hostCommand starts the child session in the new tab.
// shortcut: assumes `pig` is on the tab's PATH, upgrade when the SDK exposes the host executable.
var hostCommand = "pig"

type modelRef struct {
	Provider string `json:"provider"`
	ID       string `json:"id"`
	Name     string `json:"name,omitempty"`
}

type launchData struct {
	LaunchID          string    `json:"launchId"`
	Message           string    `json:"message,omitempty"`
	AutoSubmitSeconds int       `json:"autoSubmitSeconds"`
	ModelNotice       string    `json:"modelNotice,omitempty"`
	TargetModel       *modelRef `json:"targetModel,omitempty"`
}

var modelFlagRe = regexp.MustCompile(`^--model\s+(\S+)(?:\s+|$)`)

// parseBranchArgs reads a leading `--model <query>`; the rest is the draft message (index.ts:484).
func parseBranchArgs(raw string) (modelQuery, message string) {
	remaining := jsTrim(raw)
	if m := modelFlagRe.FindStringSubmatch(remaining); m != nil {
		modelQuery = m[1]
		remaining = strings.TrimLeft(remaining[len(m[0]):], " \t\n\r\v\f")
	}
	return modelQuery, remaining
}

func registerBranch(e *sdk.Extension) {
	cd := &countdown{}

	for _, ev := range []string{sdk.EventSessionBeforeSwitch, sdk.EventSessionBeforeFork, sdk.EventSessionBeforeTree, sdk.EventSessionTree, sdk.EventSessionShutdown} {
		e.OnEvent(ev, func(sdk.Context, map[string]any) (any, error) {
			cd.clear(nil, "")
			return nil, nil
		})
	}

	e.OnEvent(sdk.EventSessionStart, func(ctx sdk.Context, _ map[string]any) (any, error) {
		return nil, applyPendingLaunch(ctx, cd)
	})

	e.Command("branch", "Fork current session into a new Warp tab, optionally queueing --model <query> and a draft message", func(ctx sdk.Context, args string) error {
		sessionFile, err := ctx.GetSessionFile()
		if err != nil {
			return err
		}
		if sessionFile == nil {
			notifyUI(ctx, "Session is not persisted. Restart without --no-session.", "error")
			return nil
		}
		leafID, err := ctx.GetLeafID()
		if err != nil {
			return err
		}
		if leafID == nil {
			notifyUI(ctx, "No messages yet. Nothing to branch.", "error")
			return nil
		}
		modelQuery, message := parseBranchArgs(args)
		manager, err := sdk.SessionManagerOpen(ctx, *sessionFile, nil, nil)
		if err != nil {
			return err
		}
		forkFile, err := manager.CreateBranchedSession(*leafID)
		if err != nil {
			return err
		}
		if forkFile == nil {
			return errors.New("Failed to create branched session")
		}

		var launch *launchData
		if modelQuery != "" || message != "" {
			fork, err := sdk.SessionManagerOpen(ctx, *forkFile, nil, nil)
			if err != nil {
				return err
			}
			target, notice := resolveBranchModel(ctx, modelQuery)
			launch = &launchData{
				LaunchID:          fmt.Sprintf("%d-%06x", time.Now().UnixMilli(), rand.IntN(1<<24)),
				Message:           message,
				AutoSubmitSeconds: autoSubmitSeconds,
				ModelNotice:       notice,
				TargetModel:       target,
			}
			if _, err := fork.AppendCustomEntry(launchType, launch); err != nil {
				return err
			}
		}

		if err := openInWarp(ctx, *forkFile); err != nil {
			return err
		}

		notice := "Created fork and requested terminal launch"
		if launch != nil {
			var details []string
			if launch.TargetModel != nil {
				details = append(details, launch.TargetModel.Provider+"/"+launch.TargetModel.ID)
			} else if ctx.Model() != "" {
				details = append(details, ctx.ModelProvider()+"/"+ctx.Model())
			}
			if launch.Message != "" {
				details = append(details, "draft queued")
			}
			if len(details) > 0 {
				notice += " (" + strings.Join(details, " · ") + ")"
			}
		}
		notifyUI(ctx, notice, "info")
		return nil
	})
}

func notifyUI(ctx sdk.Context, message, level string) {
	if ctx.HasUI() {
		ctx.Notify(message, level)
	}
}

// warpTabConfigDir is where Warp reads Tab Configs (index.ts:1125).
func warpTabConfigDir() string {
	home, _ := os.UserHomeDir()
	if runtime.GOOS == "darwin" {
		return filepath.Join(home, ".warp", "tab_configs")
	}
	data := os.Getenv("XDG_DATA_HOME")
	if data == "" {
		data = filepath.Join(home, ".local", "share")
	}
	return filepath.Join(data, "warp-terminal", "tab_configs")
}

func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// tomlString is a JSON string literal, which is a valid TOML basic string once raw DEL is escaped (index.ts:1141).
func tomlString(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.ReplaceAll(strings.TrimSuffix(buf.String(), "\n"), "\x7f", `\u007f`)
}

var unsafeName = regexp.MustCompile(`[^a-zA-Z0-9_-]`)

// openInWarp writes a one-shot Tab Config whose startup command deletes it and resumes the fork, then opens it by URI (index.ts:1112).
func openInWarp(ctx sdk.Context, forkFile string) error {
	if os.Getenv("TERM_PROGRAM") != "WarpTerminal" {
		return errors.New("/branch opens a Warp tab; TERM_PROGRAM is not WarpTerminal")
	}
	if runtime.GOOS != "darwin" && runtime.GOOS != "linux" {
		return errors.New("Warp branch launch is supported on macOS and Linux only")
	}
	cwd := ctx.Cwd()
	configDir := warpTabConfigDir()
	name := "tmp_pi_branch_" + unsafeName.ReplaceAllString(strings.TrimSuffix(filepath.Base(forkFile), ".jsonl"), "_")
	configFile := filepath.Join(configDir, name+".toml")
	command := "rm -f -- " + shellQuote(configFile) + "; " + hostCommand + " --session " + shellQuote(forkFile)
	if strings.Contains(cwd, reservedTemplate) || strings.Contains(command, reservedTemplate) {
		return fmt.Errorf("Warp substitutes %s in Tab Configs; cannot launch from a path containing it", reservedTemplate)
	}
	if err := os.MkdirAll(configDir, 0o700); err != nil {
		return err
	}
	content := strings.Join([]string{
		`name = "Pi branch"`, "", "[[panes]]", `id = "main"`, `type = "terminal"`,
		"directory = " + tomlString(cwd), "commands = [" + tomlString(command) + "]", "",
	}, "\n")
	f, err := os.OpenFile(configFile, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return err
	}
	_, err = f.WriteString(content)
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		_ = os.Remove(configFile)
		return err
	}

	opener := "xdg-open"
	if runtime.GOOS == "darwin" {
		opener = "open"
	}
	res, err := ctx.Exec(opener, []string{"warp://tab_config/" + url.PathEscape(name)})
	if err == nil && res != nil && res.ExitCode != 0 {
		msg := res.Stderr
		if msg == "" {
			msg = res.Stdout
		}
		if msg == "" {
			msg = "Warp URI launch failed"
		}
		err = errors.New(msg)
	}
	if err != nil {
		_ = os.Remove(configFile)
	}
	return err
}

// applyPendingLaunch runs in the child: it marks the latest unapplied launch entry applied, switches the model and prefills the draft (index.ts:1248).
func applyPendingLaunch(ctx sdk.Context, cd *countdown) error {
	branch, err := ctx.SessionManager().GetBranch(nil)
	if err != nil {
		return err
	}
	launch := readLaunch(branch)
	if launch == nil {
		return nil
	}
	if err := ctx.AppendEntry(launchAppliedType, map[string]any{"launchId": launch.LaunchID}); err != nil {
		return err
	}
	if t := launch.TargetModel; t != nil {
		match, err := ctx.ModelRegistry().Find(t.Provider, t.ID)
		if err != nil {
			return err
		}
		if match != nil && (ctx.ModelProvider() != t.Provider || ctx.Model() != t.ID) {
			if switched, err := ctx.SetModel(t.Provider + "/" + t.ID); err != nil || !switched {
				notifyUI(ctx, fmt.Sprintf("Could not switch branch model to %s/%s", t.Provider, t.ID), "warning")
			}
		}
	}
	if launch.ModelNotice != "" {
		level := "warning"
		if launch.TargetModel != nil {
			level = "info"
		}
		notifyUI(ctx, launch.ModelNotice, level)
	}
	message := jsTrim(launch.Message)
	if !ctx.HasUI() || message == "" {
		return nil
	}
	ctx.SetEditorText(message)
	if launch.AutoSubmitSeconds > 0 {
		return cd.start(ctx, launch.AutoSubmitSeconds)
	}
	ctx.Notify("Draft ready in editor (auto-submit disabled)", "info")
	return nil
}

// readLaunch returns the last launch entry unless an applied entry names it (index.ts:610).
func readLaunch(entries []map[string]any) *launchData {
	var latest *launchData
	applied := map[string]bool{}
	for _, e := range entries {
		if e["type"] != "custom" {
			continue
		}
		data, _ := e["data"].(map[string]any)
		id, _ := data["launchId"].(string)
		switch e["customType"] {
		case launchAppliedType:
			if id != "" {
				applied[id] = true
			}
		case launchType:
			if id == "" {
				continue
			}
			raw, _ := json.Marshal(data)
			var l launchData
			if json.Unmarshal(raw, &l) == nil {
				latest = &l
			}
		}
	}
	if latest == nil || applied[latest.LaunchID] {
		return nil
	}
	return latest
}

// countdown is the auto-submit timer of a prefilled draft: typing or Esc cancels it, Enter submits as usual (index.ts:560).
type countdown struct {
	mu          sync.Mutex
	ctx         *sdk.Context
	sessionFile string
	stop        chan struct{}
	unsubscribe func()
}

func (c *countdown) start(ctx sdk.Context, seconds int) error {
	c.clear(nil, "")
	sessionFile, err := ctx.GetSessionFile()
	if err != nil {
		return err
	}
	if sessionFile == nil {
		ctx.Notify("Auto-submit disabled: could not determine session identity", "warning")
		return nil
	}
	ctx.SetStatus(statusKey, statusLine(ctx, seconds))
	unsubscribe, err := ctx.OnTerminalInput(func(data string) sdk.TerminalInputResult {
		switch {
		case data == "\x1b":
			c.clear(&ctx, "Auto-submit cancelled")
			return sdk.TerminalInputResult{Consume: true}
		case data == "\r" || data == "\n" || data == "\r\n":
			c.clear(&ctx, "")
		case isEditableInput(data):
			c.clear(&ctx, "Auto-submit cancelled")
		}
		return sdk.TerminalInputResult{}
	})
	if err != nil {
		return err
	}
	stop := make(chan struct{})
	c.mu.Lock()
	c.ctx, c.sessionFile, c.stop, c.unsubscribe = &ctx, *sessionFile, stop, unsubscribe
	c.mu.Unlock()
	go func() {
		t := time.NewTicker(time.Second)
		defer t.Stop()
		for remaining := seconds; ; {
			select {
			case <-stop:
				return
			case <-t.C:
				remaining--
				if remaining <= 0 {
					c.submit()
					return
				}
				ctx.SetStatus(statusKey, statusLine(ctx, remaining))
			}
		}
	}()
	return nil
}

func statusLine(ctx sdk.Context, seconds int) string {
	theme := ctx.UITheme()
	return theme.Fg("accent", fmt.Sprintf("branch auto-submit in %ds", seconds)) + " " + theme.Fg("dim", "(type or Esc to cancel)")
}

// clear stops the countdown; notice (if any) goes to ctx, or to the countdown's own context when ctx is nil (index.ts:517).
func (c *countdown) clear(ctx *sdk.Context, notice string) {
	c.mu.Lock()
	active := c.ctx
	if active == nil {
		c.mu.Unlock()
		return
	}
	close(c.stop)
	c.unsubscribe()
	c.ctx, c.stop, c.unsubscribe = nil, nil, nil
	c.mu.Unlock()
	active.ClearStatus(statusKey)
	if notice == "" {
		return
	}
	if ctx == nil {
		ctx = active
	}
	ctx.Notify(notice, "info")
}

// submit sends the draft when the session is still the one the countdown started in (index.ts:531).
func (c *countdown) submit() {
	c.mu.Lock()
	active, sessionFile := c.ctx, c.sessionFile
	c.mu.Unlock()
	if active == nil {
		return
	}
	ctx := *active
	current, err := ctx.GetSessionFile()
	if err != nil || current == nil || *current != sessionFile {
		c.clear(nil, "")
		return
	}
	text, err := ctx.GetEditorText()
	c.clear(nil, "")
	if err != nil {
		return
	}
	draft := jsTrim(text)
	if draft == "" {
		ctx.Notify("Draft is empty", "warning")
		return
	}
	ctx.SetEditorText("")
	deliverAs := ""
	if idle, err := ctx.IsIdle(); err == nil && !idle {
		deliverAs = "followUp"
	}
	if err := ctx.SendUserMessage(draft, deliverAs); err != nil && deliverAs != "" {
		_ = ctx.SendUserMessage(draft, "")
	}
}

// isEditableInput is a chunk the editor would insert or delete with (index.ts:497).
func isEditableInput(data string) bool {
	if data == "" {
		return false
	}
	if r := []rune(data); len(r) == 1 {
		c := r[0]
		return c >= 32 || c == 8 || c == 13 || c == '\n'
	}
	return data == "\r\n" || !strings.HasPrefix(data, "\x1b")
}

// ── model resolution (index.ts:259-482) ─────────────────────────────────────

func normalizeModelText(s string) string { return strings.ToLower(jsTrim(s)) }

var nonAlnum = regexp.MustCompile(`[^a-z0-9]+`)

func collapseModelText(s string) string { return nonAlnum.ReplaceAllString(normalizeModelText(s), "") }

func scoreModelCandidate(query string, c modelRef, preferredProvider string) int {
	q := normalizeModelText(query)
	if q == "" {
		return 0
	}
	fullID, id, name := normalizeModelText(c.Provider+"/"+c.ID), normalizeModelText(c.ID), normalizeModelText(c.Name)
	bonus := 0
	if preferredProvider != "" && normalizeModelText(c.Provider) == normalizeModelText(preferredProvider) {
		bonus = 750
	}
	switch {
	case fullID == q:
		return 12000 + bonus
	case id == q:
		return 11500 + bonus
	case strings.HasSuffix(fullID, "/"+q):
		return 11000 + bonus
	case strings.HasPrefix(id, q):
		return 10000 - (len(id) - len(q)) + bonus
	case strings.HasPrefix(fullID, q):
		return 9500 - (len(fullID) - len(q)) + bonus
	}
	if i := strings.Index(id, q); i != -1 {
		return 9000 - i*10 - (len(id) - len(q)) + bonus
	}
	if i := strings.Index(fullID, q); i != -1 {
		return 8000 - i*10 - (len(fullID) - len(q)) + bonus
	}
	if i := strings.Index(name, q); i != -1 {
		return 7000 - i*10 - (len(name) - len(q)) + bonus
	}
	cq := collapseModelText(query)
	if cq == "" {
		return 0
	}
	cid, cfull, cname := collapseModelText(c.ID), collapseModelText(c.Provider+"/"+c.ID), collapseModelText(c.Name)
	switch {
	case cid == cq:
		return 6500 + bonus
	case cfull == cq:
		return 6250 + bonus
	case strings.HasPrefix(cid, cq):
		return 6000 - (len(cid) - len(cq)) + bonus
	case strings.HasPrefix(cfull, cq):
		return 5500 - (len(cfull) - len(cq)) + bonus
	}
	if i := strings.Index(cid, cq); i != -1 {
		return 5000 - i*10 - (len(cid) - len(cq)) + bonus
	}
	if i := strings.Index(cfull, cq); i != -1 {
		return 4500 - i*10 - (len(cfull) - len(cq)) + bonus
	}
	if i := strings.Index(cname, cq); i != -1 {
		return 4000 - i*10 - (len(cname) - len(cq)) + bonus
	}
	return 0
}

// resolveClosestModel picks the best-scoring candidate; a `provider/` prefix scopes the search (index.ts:385).
func resolveClosestModel(query string, candidates []modelRef, preferredProvider string) *modelRef {
	q := normalizeModelText(query)
	if q == "" {
		return nil
	}
	providerQuery, idQuery := "", q
	if i := strings.Index(q, "/"); i > 0 {
		providerQuery, idQuery = q[:i], q[i+1:]
	}
	var best *modelRef
	bestScore := 0
	for i := range candidates {
		c := candidates[i]
		if providerQuery != "" && normalizeModelText(c.Provider) != providerQuery {
			continue
		}
		score := scoreModelCandidate(q, c, preferredProvider)
		if providerQuery != "" {
			score = max(score, scoreModelCandidate(idQuery, c, preferredProvider)+50)
		}
		if score <= 0 {
			continue
		}
		if best == nil || score > bestScore || score == bestScore && (len(c.ID) < len(best.ID) || len(c.ID) == len(best.ID) && c.Provider+"/"+c.ID < best.Provider+"/"+best.ID) {
			best, bestScore = &c, score
		}
	}
	return best
}

func toModelRef(m map[string]any) modelRef {
	provider, _ := m["provider"].(string)
	id, _ := m["id"].(string)
	name, _ := m["name"].(string)
	return modelRef{Provider: provider, ID: id, Name: name}
}

// modelCandidates is the session's scoped models (Pi's enabledModels, which PiG resolves itself) or, with no scope, the current provider's available models (index.ts:465).
func modelCandidates(ctx sdk.Context) []modelRef {
	var out []modelRef
	if scoped, err := ctx.ScopedModels(); err == nil {
		for _, s := range scoped {
			out = append(out, toModelRef(s.Model))
		}
	}
	if len(out) > 0 || ctx.Model() == "" {
		return out
	}
	available, _ := ctx.ModelRegistry().GetAvailable()
	for _, m := range available {
		if ref := toModelRef(m); ref.Provider == ctx.ModelProvider() {
			out = append(out, ref)
		}
	}
	return out
}

// resolveBranchModel maps the --model query to a target model and a notice for the child (index.ts:1283).
func resolveBranchModel(ctx sdk.Context, query string) (*modelRef, string) {
	if ctx.Model() == "" {
		if query != "" {
			return nil, fmt.Sprintf("Model '%s' did not resolve; branch will use the session model.", query)
		}
		return nil, ""
	}
	current := modelRef{Provider: ctx.ModelProvider(), ID: ctx.Model()}
	if info, err := ctx.GetModelInfo(); err == nil && info != nil {
		current.Name = info.Name
	}
	if query == "" {
		return &current, ""
	}
	match := resolveClosestModel(query, modelCandidates(ctx), current.Provider)
	if match == nil {
		return &current, fmt.Sprintf("Model '%s' did not resolve safely; using %s/%s", query, current.Provider, current.ID)
	}
	return match, fmt.Sprintf("Branch model: %s/%s", match.Provider, match.ID)
}
